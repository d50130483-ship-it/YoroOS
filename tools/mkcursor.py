#!/usr/bin/env python3
"""Generates kernel/cursor_data.h: the YoroOS arrow pointer.

Style: solid black arrow with a white rounded outline (triangle pointer, user reference), drawn here from geometry. Every pixel stores two anti-aliased
coverages: outline (white) and fill (black), so the kernel can alpha-blend it.
No third-party cursor artwork is used.
"""
import math, os, sys

W = H = 24
OX, OY = 1.0, 1.0            # shift the arrow inside the 24x24 box
SS = 8                       # supersampling per axis
OUTLINE = 1.45               # white outline thickness (pixels, outside the black shape)

# Pointer polygon: tip at the origin
POLY = [(0.0, 0.0), (0.0, 17.0), (12.6, 12.6)]   # plain triangle, no tail (user reference)

def inside(px, py):
    c = False
    n = len(POLY)
    j = n - 1
    for i in range(n):
        xi, yi = POLY[i]; xj, yj = POLY[j]
        if (yi > py) != (yj > py) and px < (xj - xi) * (py - yi) / (yj - yi) + xi:
            c = not c
        j = i
    return c

def dist_edge(px, py):
    best = 1e9
    n = len(POLY)
    for i in range(n):
        ax, ay = POLY[i]; bx, by = POLY[(i + 1) % n]
        dx, dy = bx - ax, by - ay
        t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
        qx, qy = ax + t * dx, ay + t * dy
        d = math.hypot(px - qx, py - qy)
        if d < best:
            best = d
    return best

def coverage(x, y):
    fill = 0; outline = 0
    total = SS * SS
    for sy in range(SS):
        for sx in range(SS):
            px = x + (sx + 0.5) / SS - OX
            py = y + (sy + 0.5) / SS - OY
            if inside(px, py):
                fill += 1
            elif dist_edge(px, py) <= OUTLINE:
                outline += 1
    return int(round(255 * outline / total)), int(round(255 * fill / total))

def main():
    rows = []
    for y in range(H):
        row = []
        for x in range(W):
            o, f = coverage(x, y)
            row.append((o, f))
        rows.append(row)
    if '--preview' in sys.argv:
        for row in rows:
            print(''.join('#' if f > 200 else ('o' if o > 100 else ('+' if o > 20 else '.')) for o, f in row))
        return
    out = os.path.join(os.path.dirname(__file__), '..', 'kernel', 'cursor_data.h')
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by tools/mkcursor.py - do not edit by hand.\n')
        fh.write(' * YoroOS arrow pointer: black fill with white outline, 24x24, anti-aliased.\n')
        fh.write(' * Each pixel is {outline_coverage, fill_coverage}, 0..255. */\n')
        fh.write('#ifndef YORO_CURSOR_DATA_H\n#define YORO_CURSOR_DATA_H\n\n')
        fh.write('#define CURSOR_W 24\n#define CURSOR_H 24\n\n')
        fh.write('static const unsigned char g_cursor_px[CURSOR_H][CURSOR_W][2] = {\n')
        for row in rows:
            fh.write('    {' + ', '.join('{%d,%d}' % (o, f) for o, f in row) + '},\n')
        fh.write('};\n\n#endif\n')
    print('wrote', os.path.normpath(out))

if __name__ == '__main__':
    main()
