#!/usr/bin/env python3
"""YoroOS font generator.
Rasterises a TTF (DejaVu Sans) into an 8-bit alpha grayscale bitmap font
used by the kernel text renderer. Supports Latin + Cyrillic + UI symbols.
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

SIZE = 15
H = 18
FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

CHARS = []
CHARS += [chr(c) for c in range(32, 127)]
CHARS += [chr(c) for c in range(0x410, 0x450)]          # А-я
CHARS += ["Ё", "ё", "«", "»", "№", "—", "–", "…", "→", "←", "↑", "↓",
          "×", "✓", "•", "·", "°", "₽", "€", "©", "®", "™", "▲", "▼", "◆", "★"]

font = ImageFont.truetype(FONT_PATH, SIZE)
ascent, descent = font.getmetrics()
assert ascent + descent <= H, (ascent, descent)
base_y = (H - (ascent + descent)) // 2

CHARS = sorted(set(CHARS), key=lambda c: ord(c))

glyphs = []
pixels = bytearray()

for ch in CHARS:
    adv = int(round(font.getlength(ch)))
    if adv <= 0:
        adv = 1
    w = max(adv, 0)
    img = Image.new("L", (w + 4, H + 6), 0)
    d = ImageDraw.Draw(img)
    d.text((0, base_y), ch, fill=255, font=font)
    # trim to advance width, keep full height
    img = img.crop((0, 0, w, H))
    data = img.tobytes()
    off = len(pixels)
    pixels += data
    glyphs.append((ord(ch), w, adv, off))

# --- emit C ---
out = []
out.append("/* Generated by tools/mkfont.py - do not edit. */")
out.append('#include "kernel.h"')
out.append("")
out.append("const unsigned char font_pixels[] = {")
for i in range(0, len(pixels), 24):
    out.append(",".join(str(b) for b in pixels[i:i+24]) + ",")
out.append("};")
out.append("")
out.append("const Glyph font_glyphs[] = {")
for cp, w, adv, off in glyphs:
    out.append("{0x%04X,%d,%d,%d}," % (cp, w, adv, off))
out.append("};")
out.append("const int font_count = %d;" % len(glyphs))
out.append("const int font_height = %d;" % H)
out.append("")
with open(sys.argv[1] if len(sys.argv) > 1 else "kernel/font_data.c", "w") as f:
    f.write("\n".join(out) + "\n")
print("font: %d glyphs, %d bytes of pixels" % (len(glyphs), len(pixels)))
