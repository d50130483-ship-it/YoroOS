#!/usr/bin/env python3
"""Render the default arrow pointer (Linux Mint / Bibata Modern Classic look).

The geometry is our own: a triangle-style arrow with a concave lower edge, black fill
and a white outline. Writes:
  src/cursor_data.h     24x24 RGBA bytes, consumed by the kernel
  cursor/preview.png    8x preview on white for review

Run from the repository root:  python3 tools/mkcursor.py
"""
import os
from PIL import Image, ImageDraw, ImageFilter

SIZE = 24          # cursor size in pixels
SS = 16            # supersampling factor
OUTLINE = 1.5      # outline width in pixels (outside the black fill)

# Arrow outline in pixel coordinates, tip at (2, 2).
POLY = [(2.0, 2.0), (2.0, 20.0), (7.0, 19.0), (10.5, 18.5), (13.5, 15.5), (17.0, 11.5)]


def render() -> Image.Image:
    big = SIZE * SS
    fill = Image.new("L", (big, big), 0)
    ImageDraw.Draw(fill).polygon([(x * SS, y * SS) for x, y in POLY], fill=255)

    r = int(round(OUTLINE * SS))
    grown = fill.filter(ImageFilter.MaxFilter(2 * r + 1))

    white = Image.new("RGBA", (big, big), (255, 255, 255, 255))
    white.putalpha(grown)
    black = Image.new("RGBA", (big, big), (0, 0, 0, 255))
    black.putalpha(fill)
    img = Image.alpha_composite(white, black)
    return img.resize((SIZE, SIZE), Image.BOX)


def main() -> None:
    img = render()
    raw = img.tobytes()
    px = [tuple(raw[i:i+4]) for i in range(0, len(raw), 4)]

    os.makedirs("src", exist_ok=True)
    os.makedirs("cursor", exist_ok=True)

    lines = [
        "/* Generated by tools/mkcursor.py. Do not edit by hand. */",
        "#ifndef YORO_CURSOR_DATA_H",
        "#define YORO_CURSOR_DATA_H",
        "",
        f"#define CURSOR_W {SIZE}",
        f"#define CURSOR_H {SIZE}",
        "",
        "/* RGBA, row-major, straight (non-premultiplied) alpha. */",
        f"static const unsigned char CURSOR_RGBA[CURSOR_W * CURSOR_H * 4] = {{",
    ]
    for row in range(SIZE):
        cells = []
        for col in range(SIZE):
            r, g, b, a = px[row * SIZE + col]
            cells.append(f"{r},{g},{b},{a}")
        lines.append("    " + ",".join(cells) + ",")
    lines += ["};", "", "#endif", ""]
    with open("src/cursor_data.h", "w", encoding="ascii") as f:
        f.write("\n".join(lines))

    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    bg.alpha_composite(img)
    bg.convert("RGB").resize((SIZE * 8, SIZE * 8), Image.NEAREST).save("cursor/preview.png")
    print("wrote src/cursor_data.h and cursor/preview.png")


if __name__ == "__main__":
    main()
