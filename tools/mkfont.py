#!/usr/bin/env python3
"""YoroOS 0.2 multi-face anti-aliased TTF rasterizer with tight vertical crop.
Generates 5 crisp alpha-blended font faces from DejaVu Sans / Sans Bold / Sans Mono:
  0 = FONT_UI    (15px DejaVuSans,      line_h 18)
  1 = FONT_SMALL (12px DejaVuSans,      line_h 15)
  2 = FONT_TITLE (21px DejaVuSans-Bold, line_h 26)
  3 = FONT_HERO  (36px DejaVuSans,      line_h 44)
  4 = FONT_MONO  (13px DejaVuSansMono,  line_h 17)
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SANS = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
MONO = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"

BASE_CHARS = (
    [chr(c) for c in range(32, 127)]
    + [chr(c) for c in range(0x0410, 0x0450)]
    + [
        "Ё", "ё", "«", "»", "№", "—", "–", "…", "→", "←", "↑", "↓",
        "×", "✓", "✕", "•", "·", "°", "₽", "€", "©", "®", "™",
        "▲", "▼", "◀", "▶", "◆", "★", "☆", "±", "÷", "√", "∞",
        "─", "│", "┌", "┐", "└", "┘", "├", "┤", "┬", "┴", "┼",
        "═", "║", "╔", "╗", "╚", "╝", "█", "▓", "▒", "░", "■", "□",
    ]
)

HERO_CHARS = (
    [chr(c) for c in range(32, 127)]
    + [chr(c) for c in range(0x0410, 0x0450)]
    + ["Ё", "ё", "«", "»", "№", "—", "–", "…", "•", "·", "°", "×", "÷", "±", "%"]
)

FACES = [
    ("ui",    SANS, 15, 18, BASE_CHARS),
    ("small", SANS, 12, 15, BASE_CHARS),
    ("title", BOLD, 21, 26, BASE_CHARS),
    ("hero",  SANS, 36, 44, HERO_CHARS),
    ("mono",  MONO, 13, 17, BASE_CHARS),
]

all_pixels = bytearray()
face_glyphs = []
face_meta = []

for name, path, size, line_h, charset in FACES:
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    total_h = max(line_h, ascent + descent)
    base_y = max(0, (line_h - (ascent + descent)) // 2)
    chars = sorted(set(charset), key=lambda c: ord(c))
    glyphs = []
    for ch in chars:
        adv = max(1, int(round(font.getlength(ch))))
        bbox = font.getbbox(ch)
        gw = max(adv, (int(bbox[2]) + 1) if bbox else adv, 1)
        canvas = Image.new("L", (gw + 4, total_h + 4), 0)
        d = ImageDraw.Draw(canvas)
        d.text((0, base_y), ch, fill=255, font=font)
        cropped = canvas.crop((0, 0, gw, line_h))
        nz = cropped.getbbox()
        if nz is None:
            glyphs.append((ord(ch), 0, 0, 0, adv, 0))
        else:
            x0, y0, x1, y1 = nz
            sub = cropped.crop((x0, y0, x1, y1))
            off = len(all_pixels)
            all_pixels += sub.tobytes()
            glyphs.append((ord(ch), x0, y0, x1 - x0, y1 - y0, adv, off))
            continue
    start_idx = sum(len(g) for g in face_glyphs)
    face_glyphs.append(glyphs)
    face_meta.append((name, line_h, start_idx, len(glyphs)))

out = [
    "/* Generated by tools/mkfont.py - do not edit manually. */",
    '#include "kernel.h"',
    "",
    "const unsigned char font_pixels[] = {",
]
for i in range(0, len(all_pixels), 28):
    out.append(",".join(str(b) for b in all_pixels[i : i + 28]) + ",")
out.append("};")
out.append("")
out.append("const Glyph font_glyphs[] = {")
for glyphs in face_glyphs:
    for item in glyphs:
        if len(item) == 6:
            cp, _, _, _, adv, off = item
            out.append("{0x%04X,0,0,0,0,%d,0}," % (cp, adv))
        else:
            cp, xoff, yoff, w, h, adv, off = item
            out.append("{0x%04X,%d,%d,%d,%d,%d,%u}," % (cp, xoff, yoff, w, h, adv, off))
out.append("};")
out.append("")
out.append("const FontFace font_faces[5] = {")
for name, line_h, start_idx, count in face_meta:
    out.append("    { %d, %d, %d }, /* %s */" % (line_h, start_idx, count, name))
out.append("};")
out.append("const int font_count = %d;" % len(face_glyphs[0]))
out.append("const int font_height = 18;")
out.append("")

target = sys.argv[1] if len(sys.argv) > 1 else "kernel/font_data.c"
with open(target, "w") as f:
    f.write("\n".join(out))

print(
    "mkfont: %d faces, %d total glyphs, %.1f KiB pixel atlas"
    % (len(face_meta), sum(len(g) for g in face_glyphs), len(all_pixels) / 1024.0)
)
